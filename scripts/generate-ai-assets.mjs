export function validateManifest(m) {
  validateShape(m, productSchema);
  assert.deepEqual(m.freeCv.formats, ['pdf']);
  assert.deepEqual(m.freeCv.styles, ['color', 'plain']);
  assert.deepEqual(m.languages.uiLocaleIds, ['en','en-GB','hi','ar','zh-CN','es-ES','fr-FR','ja']);
  assert.deepEqual(m.languages.cvHeadingLocaleIds, ['en','fr','de','es']);
  assert.equal(new Set(m.publicPaths).size, m.publicPaths.length);
  assert.equal(m.publicPaths.length, m.sitemap.expectedUrlCount);
  assert.deepEqual(m.languages.publicContentLocaleIds,registry.activeLocales);
  assert.equal(m.languages.publicContentPageCount,registry.activeLocales.length*registry.pages.length);
  assert.equal(m.sitemap.localeIds.length, m.sitemap.hreflangTags.length);
  for (const p of m.publicPaths) assert.ok(p.startsWith('/') && !p.includes('?') && !p.includes('#') && !p.startsWith('/api/') && !p.startsWith('/c/'));
  assert.equal(new Set(m.languages.uiLocaleIds.map(l => l.split('-')[0])).size, m.languages.baseLanguageCount);
  return m;
}
export function validatePolicy(p) {
  assert.deepEqual(Object.keys(p).sort(), ['schemaVersion','trainingPolicy','protectedPaths','sitemapUrl','note'].sort());
  assert.equal(p.schemaVersion, 1);
  assert.ok(['allow','deny'].includes(p.trainingPolicy));
  assert.deepEqual(p.protectedPaths, ['/api/','/c/','/dashboard']);
  assert.equal(p.sitemapUrl, 'https://formzalo.com/sitemap.xml');
  assert.equal(typeof p.note, 'string');
}
export function renderRobots(p = policy, registry = directory) {
  validatePolicy(p); validateDirectory(registry);
  const groups = [{ token: '*', deny: false }];
  const seen = new Set();
  for (const platform of registry.platforms) for (const agent of platform.crawlers.agents) {
    assert.ok(!seen.has(agent.token), `duplicate policy token ${agent.token}`); seen.add(agent.token);
    groups.push({ token: agent.token, deny: p.trainingPolicy === 'deny' && agent.purposes.includes('training') });
  }
  const lines = ['# Generated by scripts/generate-ai-assets.mjs; do not hand-edit.',
    `# Verified training-control policy: ${p.trainingPolicy}. Unknown providers use wildcard rules.`,
    '# Google-Extended also controls some Gemini grounding; it is not a distinct HTTP crawler.',
    '# User-requested fetchers may apply robots differently. These directives are not access control.', ''];
  for (const group of groups) {
    lines.push(`User-agent: ${group.token}`, group.deny ? 'Disallow: /' : 'Allow: /', ...p.protectedPaths.map(path => `Disallow: ${path}`), '');
  }
  lines.push(`Sitemap: ${p.sitemapUrl}`, '');
  return lines.join('\n');
}
